#!/usr/bin/env python3
"""
Run the standalone router -> retrieve -> calculate -> synthesize pipeline
(src/generation/agent.py) directly against Weaviate + OpenAI — no FastAPI
server required.

This exercises the same router (src/generation/router.py) and calculator
(src/generation/tools.py) that /chat wires in, but through agent.py's own
bare-bones retrieval rather than /chat's fully configurable one — useful for
sanity-checking a question's routing decision, tool arguments, and computed
result in isolation.

Usage:
    # Trend question (Multi-Doc RAG, needs analyze_trend)
    python scripts/run_agent.py "How has Apple's total net sales changed over time?"

    # Share-of-total question (needs calculate_share_of_total)
    python scripts/run_agent.py "For Q3 2023, what proportion of NVIDIA's revenue was generated by its data center business?"

    # Plain lookup (rag_only, no calculation)
    python scripts/run_agent.py "Did Amazon report any major stock buybacks in its Q3 2023 10-Q?"
"""
import argparse
import logging
import sys
from pathlib import Path

# Allow running from the repo root
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from dotenv import load_dotenv

load_dotenv()

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s  [%(levelname)s]  %(name)s – %(message)s",
    datefmt="%H:%M:%S",
)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Run the deterministic router+calculator RAG pipeline on one question"
    )
    parser.add_argument("query", help="The question to answer")
    args = parser.parse_args()

    from src.config import Config
    from src.generation.agent import answer_question

    result = answer_question(args.query, Config())

    print("\n" + "=" * 60)
    print(f"  Path        : {result.path}")
    print(f"  Sources     : {len(result.sources)}")
    if result.calculation is not None:
        import json
        print(f"  Calculation :\n{json.dumps(result.calculation, indent=4)}")
    print("=" * 60)
    print(f"\n{result.answer}\n")

    if result.sources:
        print("-" * 60)
        print("Sources:")
        for i, chunk in enumerate(result.sources, start=1):
            print(f"  [{i}] {chunk.company} {chunk.quarter} {chunk.year} "
                  f"| {chunk.source_file} | p.{chunk.page_start}-{chunk.page_end}")


if __name__ == "__main__":
    main()
